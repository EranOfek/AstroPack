function stmts = pg_sql_schema(tbl, history)
%PG_SQL_SCHEMA  DDL statements (cellstr, one statement each) for a status table.
%   Idempotent: safe to run on an existing installation.
tbl  = pg_ident(tbl);
base = regexprep(tbl, '^.*\.', '');           % unqualified name for triggers/indexes
logt = [tbl '_log'];

stmts = {
 ['CREATE TABLE IF NOT EXISTS ' tbl ' (' ...
  ' folder     text COLLATE "C" PRIMARY KEY,' ...           % "C": fast prefix LIKE via the PK index
  ' status     text        NOT NULL,' ...
  ' updated    timestamptz NOT NULL DEFAULT now(),' ...
  ' updated_by text        NOT NULL DEFAULT current_user)']
 ['CREATE INDEX IF NOT EXISTS ' base '_status_idx ON ' tbl ' (status, folder)']
 ['CREATE OR REPLACE FUNCTION ' tbl '_touch_fn() RETURNS trigger LANGUAGE plpgsql AS $f$ ' ...
  'BEGIN NEW.updated := now(); NEW.updated_by := current_user; RETURN NEW; END $f$']
 ['DROP TRIGGER IF EXISTS ' base '_touch ON ' tbl]
 ['CREATE TRIGGER ' base '_touch BEFORE UPDATE ON ' tbl ' FOR EACH ROW ' ...
  'WHEN (OLD.status IS DISTINCT FROM NEW.status) EXECUTE FUNCTION ' tbl '_touch_fn()']
 };

if history
    stmts = [stmts; {
     ['CREATE TABLE IF NOT EXISTS ' logt ' (' ...
      ' id         bigserial PRIMARY KEY,' ...
      ' folder     text COLLATE "C" NOT NULL,' ...
      ' old_status text,' ...
      ' new_status text,' ...
      ' changed    timestamptz NOT NULL DEFAULT now(),' ...
      ' changed_by text        NOT NULL DEFAULT current_user)']
     ['CREATE INDEX IF NOT EXISTS ' base '_log_folder_idx ON ' logt ' (folder, id)']
     ['CREATE OR REPLACE FUNCTION ' tbl '_log_fn() RETURNS trigger LANGUAGE plpgsql AS $f$ ' ...
      'BEGIN ' ...
      'IF TG_OP = ''DELETE'' THEN ' ...
      '  INSERT INTO ' logt ' (folder, old_status, new_status) VALUES (OLD.folder, OLD.status, NULL); ' ...
      'ELSIF TG_OP = ''UPDATE'' THEN ' ...
      '  IF NEW.status IS DISTINCT FROM OLD.status THEN ' ...
      '    INSERT INTO ' logt ' (folder, old_status, new_status) VALUES (NEW.folder, OLD.status, NEW.status); ' ...
      '  END IF; ' ...
      'ELSE ' ...
      '  INSERT INTO ' logt ' (folder, old_status, new_status) VALUES (NEW.folder, NULL, NEW.status); ' ...
      'END IF; ' ...
      'RETURN NULL; END $f$']
     ['DROP TRIGGER IF EXISTS ' base '_log ON ' tbl]
     ['CREATE TRIGGER ' base '_log AFTER INSERT OR UPDATE OR DELETE ON ' tbl ' FOR EACH ROW ' ...
      'EXECUTE FUNCTION ' tbl '_log_fn()']
     }];
else
    stmts = [stmts; {['DROP TRIGGER IF EXISTS ' base '_log ON ' tbl]}];
end
end
