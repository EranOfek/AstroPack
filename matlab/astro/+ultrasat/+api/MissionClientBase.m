    % It handles authentication, session management, and various API operations.
    %
    % The class is designed to be extended by:
    %   - MissionClient: For real API communication with the backend server
    %   - MissionClientSim: For simulation and testing purposes
    %
    % Key Features:
    %   - Authentication and session management
    %   - Key-value store operations
