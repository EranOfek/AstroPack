        function response = login(obj, Params)
            % Authenticates a user with the mission control API.
            %
            % Parameters:
            %   Params - Instance of MissionApiModels.LoginParams containing:
            %     .user (string) - User name for authentication
            %     .password (string) - Password for authentication
            %
            % Returns:
            %   response - Structure containing authentication result with fields:
            %     .status - Status of the operation ('ok' or 'error')
            %     .message - Description message
            %     .ok - Boolean indicating success (true) or failure (false)
            %     .user - (if successful) User information structure
            arguments
                obj
                Params
            end
            
            usersFile = fullfile(obj.DbPath, 'users.json');
            currentUserFile = fullfile(obj.DbPath, 'current_user.json');
            response = struct();
        
            % Load users from JSON
            users = obj.readFile(usersFile);
            if isempty(fieldnames(users))
                response.status = 'error';
                response.message = 'Users database not found.';
                response.ok = false;
                return;
            end
        
            % Find user and verify password
            user = [];
            for i = 1:numel(users)
                if strcmp(users(i).UserName, Params.user) && strcmp(users(i).Password, Params.password)
                    user = users(i);
                    break;
                end
            end
        
            if isempty(user)
                obj.msglog('login: Invalid username or password for user=%s', Params.user);
                response.status = 'error';
                response.message = 'Invalid username or password.';
                response.ok = false;
            else
                obj.msglog('login: User %s logged in successfully.', Params.user);
                response.status = 'ok';
                response.user = user;
        
                % Update current_user.json
                currentUser = struct('UserName', Params.user, 'Role', user.Role);
                fid = fopen(currentUserFile, 'w');
                fwrite(fid, jsonencode(currentUser, 'PrettyPrint', true), 'char');
                fclose(fid);
        
                response.ok = true;
            end
        end


        function response = logout(obj, Params)
            % Logs out the current user from the mission control API.
            %
            % Parameters:
            %   Params - Instance of MissionApiModels.LogoutParams containing:
            %     .user (string) - Currently logged-in user name to verify
            %
            % Returns:
            %   response - Structure containing logout result with fields:
            %     .status - Status of the operation ('ok' or 'error')
            %     .message - Description message
            %     .ok - Boolean indicating success (true) or failure (false) 
            arguments
                obj
                Params
            end
            
            currentUserFile = fullfile(obj.DbPath, 'current_user.json');
            response = struct();
        
            % Load current user and verify
            currentUser = obj.readFile(currentUserFile);
            if isempty(fieldnames(currentUser))
                obj.msglog('logout: Current user file not found at %s', currentUserFile);
                response.status = 'error';
                response.message = 'No user currently logged in.';
                response.ok = false;
                return;
            end
        
            if ~strcmp(currentUser.UserName, Params.user)
                obj.msglog('logout: User %s is not currently logged in.', Params.user);
                response.status = 'error';
                response.message = 'User not logged in.';
                response.ok = false;
                return;
            end
        
            % Clear current user
            fid = fopen(currentUserFile, 'w');
            fwrite(fid, jsonencode(struct('UserName', '', 'Role', ''), 'PrettyPrint', true), 'char');
            fclose(fid);
        
            obj.msglog('logout: User %s logged out successfully.', Params.user);
            response.status = 'ok';
            response.ok = true;
        end

