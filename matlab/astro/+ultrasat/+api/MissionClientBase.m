    %   PlanData - Instance of ultrasat.api.PlanData containing current plan information
    %   ApprovedTargetsStartTime - Start time for approved targets
    %   ApprovedTargetsEndTime - End time for approved targets
    %
    % Notes:
    %   - This class is abstract and should not be instantiated directly
    %   - All API calls are logged to the specified log file
    %   - Session management is handled automatically
    %   - Error handling is consistent across all methods
    %   - PlanData property is maintained for backward compatibility with uplanner
    %   - Time conversions are handled automatically (UTC format)

    
